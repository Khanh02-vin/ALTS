// Builds the SvelteKit app with WEB_ADAPTER=node so svelte.config.js picks
// adapter-node and writes to build-node/ — the RAG sidecar that the Tauri
// desktop app spawns on 127.0.0.1. Leaves the default static build in
// build/ (Tauri frontendDist) untouched.
//
// A wrapper script instead of an inline `WEB_ADAPTER=node vite build` in
// package.json because `VAR=value cmd` does not run under cmd.exe on Windows,
// and the same script is invoked by tauri.conf beforeBuildCommand on all OSes.
import { writeFile } from "node:fs/promises";

process.env.WEB_ADAPTER = "node";
const { build } = await import("vite");
await build();

// adapter-node's own entry defaults HOST to 0.0.0.0. Tauri always sets
// HOST=127.0.0.1 when it spawns the sidecar, but running the artefact by hand
// (debugging, an E2E harness, a mis-built package) would publish the playlist
// store to the whole LAN. Emit a sidecar entry that pins loopback by default;
// set SIDECAR_ALLOW_REMOTE=1 deliberately if a remote bind is ever wanted.
await writeFile(
  new URL("./build-node/sidecar.mjs", import.meta.url),
  `// Generated by build-node.mjs — do not edit.
process.env.HOST ??= process.env.SIDECAR_ALLOW_REMOTE === "1" ? "0.0.0.0" : "127.0.0.1";
await import("./index.js");
`,
  "utf8",
);
